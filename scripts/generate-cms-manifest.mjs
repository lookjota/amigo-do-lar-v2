import { writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const output = resolve('src/apps/amigo-do-lar/content-cms/generatedContent.ts')
const manifestUrl = process.env.CMS_CONTENT_MANIFEST_URL

if (!manifestUrl) {
  console.warn('CMS_CONTENT_MANIFEST_URL is not configured; remote CMS routes will be skipped.')
  await writeFile(output, '// Generated by scripts/generate-cms-manifest.mjs. Kept empty for offline builds.\nexport const generatedContent: unknown[] = []\n')
} else {
  const response = await fetch(manifestUrl, { signal: AbortSignal.timeout(15_000) })
  if (!response.ok) throw new Error(`CMS route manifest failed with HTTP ${response.status}.`)
  const routes = await response.json()
  if (!Array.isArray(routes)) throw new Error('CMS route manifest must be an array.')
  const base = manifestUrl.replace(/\/content\/public\/routes\/?(?:\?.*)?$/, '')
  const posts = await Promise.all(routes.filter((route) => route?.index === true && typeof route.path === 'string').map(async (route) => {
    const slug = route.path.match(/^\/conteudos\/([a-z0-9]+(?:-[a-z0-9]+)*)$/)?.[1]
    if (!slug) throw new Error(`Invalid CMS route path: ${String(route.path)}`)
    const postResponse = await fetch(`${base}/content/public/posts/${slug}`, { signal: AbortSignal.timeout(15_000) })
    if (!postResponse.ok) throw new Error(`CMS post ${slug} failed with HTTP ${postResponse.status}.`)
    const payload = await postResponse.json()
    return payload.post
  }))
  await writeFile(output, `// Generated by scripts/generate-cms-manifest.mjs.\nexport const generatedContent: unknown[] = ${JSON.stringify(posts, null, 2)}\n`)
  console.log(`Generated build data for ${posts.length} published CMS routes.`)
}
